def build_entries() -> list[dict]:
    entries: list[dict] = []
    for spec in SUPPLEMENTS:
        for number, text in enumerate(spec["articles"], start=1):
            label = f"第{int_to_cn(number)}条"
            if spec["label_style"] == "original_item":
                label += f"（原文第{int_to_cn(number)}项）"
            entries.append(
                {
                    "id": f"{spec['id_prefix']}-{number:04d}",
                    "law_name": spec["law_name"],
                    "doc_type": spec["doc_type"],
                    "article_no": number,
                    "article_label": label,
                    "chapter": "",
                    "section": "",
                    "text": text,
                    "is_valid": True,
                    "effective_date": spec["effective_date"],
                    "version_date": spec["version_date"],
                    "source": f"{spec['source']}（补充入库）",
                }
            )
    return entries


def main() -> int:
    load_dotenv()
    new_entries = build_entries()
    corpus_path = ROOT / "data/corpus/all.jsonl"
    existing = [
        json.loads(line)
        for line in corpus_path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    supplement_laws = {spec["law_name"] for spec in SUPPLEMENTS}
    kept = [doc for doc in existing if doc.get("law_name") not in supplement_laws]
    merged = [*kept, *new_entries]

    with corpus_path.open("w", encoding="utf-8", newline="\n") as handle:
        for doc in merged:
            handle.write(json.dumps(doc, ensure_ascii=False) + "\n")

    print(f"[+] 补充 {len(new_entries)} 条，语料总计 {len(merged)} 条")
    for spec in SUPPLEMENTS:
        print(f"    {spec['law_name']}: {len(spec['articles'])} 条")

    index_dir = ROOT / "data/index/all"
    previous = (
        VectorIndex.load(index_dir)
        if (index_dir / "vectors.npy").exists()
        else None
    )
    embedder = build_embedder("auto")
    index, stats = VectorIndex.build_incremental(
        merged, embedder, previous=previous
    )
    meta = previous.meta if previous is not None else {}
    meta.update(
        {
            "embedder_provider": os.environ.get("LEGALQA_EMBEDDING_PROVIDER", ""),
            "embedder_model": os.environ.get("LEGALQA_EMBEDDING_MODEL", ""),
            "embedder_dimension": index.dim,
            "corpus": "data/corpus/all.jsonl",
        }
    )
    index.save(index_dir, meta=meta)
    print(
        f"[+] 索引重建完成：复用 {stats.reused}，新向量化 {stats.embedded}，"
        f"移除 {stats.removed}，总计 {len(index)} 条 × {index.dim} 维"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
