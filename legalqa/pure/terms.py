# 按 key 长度降序，优先匹配长词（「拖欠工资」先于「工资」）
_SORTED_KEYS = sorted(TERM_MAP, key=len, reverse=True)


def matched_terms(query: str, limit: int = 6) -> list[str]:
    """返回 query 里命中的术语（去重、保序、限量）。

    限量的理由：命中的术语太多会把检索串稀释成关键词堆，反而降低相关性。
    """
    if not query:
        return []
    seen: list[str] = []

    # 先跑正则（能覆盖中间插字的变体），再跑精确子串
    for pattern, terms in _EXTRA_PATTERNS:
        if pattern.search(query):
            for term in terms.split():
                if term not in seen:
                    seen.append(term)
        if len(seen) >= limit:
            return seen[:limit]

    for key in _SORTED_KEYS:
        if key in query:
            for term in TERM_MAP[key].split():
                if term not in seen:
                    seen.append(term)
        if len(seen) >= limit:
            break
    return seen[:limit]


def expand_terms(query: str, limit: int = 6) -> str:
    """把命中的法律术语**追加**到原 query 后面。

    追加而非替换：口语词携带情境信息（「白送」隐含无偿），术语提供检索锚点，
    两者都要保留。
    """
    text = (query or "").strip()
    if not text:
        return text
    terms = matched_terms(text, limit=limit)
    if not terms:
        return text
    return f"{text} {' '.join(terms)}"
