# 7. LLM 参数（§9.3）
# ---------------------------------------------------------------------------
# 法律问答要稳定、保守。实测（34 条用例）：
#   temperature=0.1 跑三次 → 88.2% / 82.4% / 82.4%（稳定失败 3 条、偶发失败 5 条）
#   temperature=0   跑一次 → 91.2%
# 低温不仅更可重复，准确率也更高——高温度下模型更"活跃"，
# 容易补充记忆里的条文，导致引用不可溯源。
